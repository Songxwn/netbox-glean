let currentLanguage = detectLanguage();

function detectLanguage() {
  try {
    const saved = localStorage.getItem(I18N_STORAGE_KEY);
    if (saved === 'zh' || saved === 'en') return saved;
  } catch (_) { /* storage unavailable */ }
  const nav = String(navigator.language || 'zh').toLowerCase();
  return nav.startsWith('zh') ? 'zh' : 'en';
}

function currentLang() {
  return currentLanguage;
}

// t looks up a message and interpolates {name} style parameters.
function t(key, params) {
  const dict = messages[currentLanguage] || messages.zh;
  let text = dict[key] ?? messages.zh[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

// applyStaticI18n refreshes all data-i18n annotated nodes in index.html.
function applyStaticI18n() {
  document.documentElement.lang = currentLanguage === 'zh' ? 'zh-CN' : 'en';
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((node) => {
    node.setAttribute('aria-label', t(node.dataset.i18nAria));
  });
  const btn = document.getElementById('btn-lang');
  if (btn) btn.textContent = currentLanguage === 'zh' ? 'English' : '中文';
}

// setLang persists the choice and re-renders the UI (refreshLanguage lives in app.js).
function setLang(next) {
  if (next !== 'zh' && next !== 'en' || next === currentLanguage) return;
  currentLanguage = next;
  try {
    localStorage.setItem(I18N_STORAGE_KEY, next);
  } catch (_) { /* storage unavailable */ }
  if (typeof refreshLanguage === 'function') refreshLanguage();
}
